#!/usr/bin/env python3
"""Bundle each scope into one minified stylesheet in dist/.

For every scope (a folder in src/ with tokens/<scope>.resolver.json), the script reads
src/<scope>/<scope>.css and writes dist/eis-<scope>.min.css:

- It replaces each local @import with the content of the file, recursively.
- It keeps remote @import rules (the fonts) and moves them to the top of the file.
- It removes comments and the whitespace that has no effect. Strings stay as they are.

The result has no local @import, so a page links one file and loads it in one request.

Usage:
  python3 scripts/build-css.py           write dist/
  python3 scripts/build-css.py --check   exit 1 if dist/ is not up to date

Standard library only.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src"
DIST = ROOT / "dist"

IMPORT = re.compile(r"""@import\s+(?:url\(\s*(["']?)(?P<a>.*?)\1\s*\)|(["'])(?P<b>.*?)\3)\s*(?P<cond>[^;]*);""")
REMOTE = re.compile(r"^(https?:)?//")


def scopes() -> list[str]:
    return sorted(p.name for p in SRC.iterdir()
                  if p.name != "shared" and (p / "tokens" / f"{p.name}.resolver.json").exists())


def strip_comments(css: str) -> str:
    out, i, n = [], 0, len(css)
    while i < n:
        c = css[i]
        if c in "\"'":
            j = i + 1
            while j < n and css[j] != c:
                j += 2 if css[j] == "\\" else 1
            out.append(css[i:j + 1])
            i = j + 1
        elif css.startswith("/*", i):
            end = css.find("*/", i + 2)
            if end < 0:
                raise ValueError("comment without an end")
            i = end + 2
        else:
            out.append(c)
            i += 1
    return "".join(out)


def inline(path: Path, remote: list[str], seen: set[Path]) -> str:
    path = path.resolve()
    if path in seen:
        raise ValueError(f"circular @import: {path.relative_to(ROOT)}")
    css = strip_comments(path.read_text(encoding="utf-8"))

    def replace(m: re.Match) -> str:
        href, condition = m.group("a") or m.group("b"), m.group("cond").strip()
        if REMOTE.match(href):
            rule = m.group(0).strip()
            if rule not in remote:
                remote.append(rule)
            return ""
        if condition:
            raise ValueError(f"@import with a media or layer condition is not supported: {m.group(0)}")
        target = path.parent / href
        if not target.exists():
            raise FileNotFoundError(f"{path.relative_to(ROOT)} imports a missing file: {href}")
        return inline(target, remote, seen | {path})

    return IMPORT.sub(replace, css)


def minify(css: str) -> str:
    # Split into strings and code. Change the code only.
    parts = re.split(r"""("(?:\\.|[^"\\])*"|'(?:\\.|[^'\\])*')""", css)
    for k in range(0, len(parts), 2):
        s = re.sub(r"\s+", " ", parts[k])
        s = re.sub(r"\s*([{};,>~])\s*", r"\1", s)  # no meaning around these characters
        s = re.sub(r":\s+", ":", s)                 # a space before ':' can be a combinator: keep it
        parts[k] = s
    css = "".join(parts)
    css = re.sub(r";+}", "}", css)
    css = re.sub(r"[^{}]+\{\}", "", css)            # empty rules
    return css.strip()


def build(scope: str) -> str:
    remote: list[str] = []
    body = minify(inline(SRC / scope / f"{scope}.css", remote, set()))
    head = "".join(minify(r) for r in remote)
    return f"/*! eis-ds · {scope} · generated by scripts/build-css.py from src/. Do not edit. */\n{head}{body}\n"


def main() -> int:
    check = "--check" in sys.argv[1:]
    DIST.mkdir(exist_ok=True)
    stale = []
    for scope in scopes():
        out = DIST / f"eis-{scope}.min.css"
        css = build(scope)
        if check:
            if not out.exists() or out.read_text(encoding="utf-8") != css:
                stale.append(out.relative_to(ROOT))
            continue
        out.write_text(css, encoding="utf-8")
        print(f"{out.relative_to(ROOT)}  {len(css.encode()):,} bytes")
    if stale:
        print("Not up to date. Run python3 scripts/build-css.py:", *stale, sep="\n  ")
        return 1
    if check:
        print("dist/ is up to date.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
