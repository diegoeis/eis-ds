#!/usr/bin/env python3
"""build-icons.py — writes src/shared/css/icons.css from Lucide.

Some icons belong to an element, not to the content of a page: the open/closed marker of a
disclosure, the check of a done list, the arrow of the sidebar toggle. The CSS draws them, so a
page writes no markup for them. This script reads those icons from lucide-static (pinned
version, ISC licence) and writes each one as a custom property that holds a data URI:

  --icon-plus: url("data:image/svg+xml,...");

A rule uses it as a mask, so the icon takes the text colour:

  .x::after{content:"";background:currentColor;mask:var(--icon-plus) center / contain no-repeat}

Usage:
  python3 scripts/build-icons.py          fetch the icons and write the file
  python3 scripts/build-icons.py --check  fail if the file is not what the list below gives

A native <select> cannot hold a pseudo-element, so its icon is a background image, which cannot
take currentColor. INKED lists those icons: the script writes a copy with the stroke in the colour of
a token (--icon-chevron-down-ink). Run build-tokens.py first.

Add an icon: put its Lucide name in ICONS and run the script. Never edit icons.css by hand.
Change LUCIDE together with the version the pages load (docs/manual/elements.md, "Icons").
"""
from __future__ import annotations

import re
import sys
import urllib.parse
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "shared" / "css" / "icons.css"
LUCIDE = "1.66.0"
ICONS = ["plus", "minus", "check", "chevron-left", "chevron-down", "x"]
# icons drawn where a mask does not work (a native <select> has no pseudo-element): the stroke takes
# the colour of a token, read from src/shared/css/tokens.css. Written as --icon-<name>-<token>
INKED = {"chevron-down": "ink"}
TOKENS = ROOT / "src" / "shared" / "css" / "tokens.css"
URL = "https://unpkg.com/lucide-static@{v}/icons/{name}.svg"


def fetch(name: str) -> str:
    with urllib.request.urlopen(URL.format(v=LUCIDE, name=name), timeout=30) as r:
        return r.read().decode("utf-8")


def compact(svg: str) -> str:
    svg = re.sub(r"<!--.*?-->", "", svg, flags=re.S)
    svg = re.sub(r'\s(class|width|height)="[^"]*"', "", svg)
    svg = re.sub(r"\s+", " ", svg).strip()
    svg = re.sub(r"\s*(/?>)\s*", r"\1", svg)
    svg = re.sub(r">\s+<", "><", svg)
    return svg.replace('"', "'")


def data_uri(svg: str) -> str:
    return "data:image/svg+xml," + urllib.parse.quote(svg, safe=" '/=:-,.")


def token_hex(name: str) -> str:
    """Follow var() references in the generated tokens.css until a hex value."""
    css = TOKENS.read_text(encoding="utf-8")
    value = f"var(--{name})"
    while value.startswith("var("):
        ref = value[4:-1]
        m = re.search(rf"^\s*{re.escape(ref)}:\s*([^;]+);", css, flags=re.M)
        if not m:
            sys.exit(f"token {ref} not found in {TOKENS.relative_to(ROOT)}")
        value = m.group(1).strip()
    return value


def build() -> str:
    svgs = {n: compact(fetch(n)) for n in ICONS}
    lines = [f'  --icon-{n}:url("{data_uri(svg)}");' for n, svg in svgs.items()]
    for n, tok in INKED.items():
        svg = svgs[n].replace("stroke='currentColor'", f"stroke='{token_hex(tok)}'")
        lines.append(f'  --icon-{n}-{tok}:url("{data_uri(svg)}");')
    head = (f"/* eis-ds · shared/css/icons.css\n"
            f"   GENERATED by scripts/build-icons.py from lucide-static@{LUCIDE} (ISC licence). Never edit by hand.\n"
            f"   Icons that the CSS draws for an element (mask + currentColor). Content icons use <i data-lucide>. */\n")
    return head + ":root{\n" + "\n".join(lines) + "\n}\n"


def main() -> int:
    css = build()
    if "--check" in sys.argv:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != css:
            print(f"{OUT.relative_to(ROOT)} is out of date. Run python3 scripts/build-icons.py")
            return 1
        print(f"{OUT.relative_to(ROOT)} is up to date.")
        return 0
    OUT.write_text(css, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(ICONS)} icons, lucide-static@{LUCIDE})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
